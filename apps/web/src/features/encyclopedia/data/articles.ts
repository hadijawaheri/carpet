function readingMinutes(article: ArticleDraft): number {
  const text = [
    article.excerpt,
    ...article.sections.flatMap((s) => [s.heading, ...s.paragraphs]),
  ].join(" ");
  const words = text.split(/\s+/).filter(Boolean).length;
  return Math.max(1, Math.ceil(words / WORDS_PER_MINUTE));
}

export const articles: Article[] = drafts.map((draft) =>
  articleSchema.parse({ ...draft, readingMinutes: readingMinutes(draft), isDraft: true }),
);

export const getArticle = (slug: string): Article | null =>
  articles.find((article) => article.slug === slug) ?? null;
